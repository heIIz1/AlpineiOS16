# postmarketOS v26.06 base + Phosh on the VM's existing ARM64 UEFI Linux platform.
set -eu
exec > /dev/ttyAMA0 2>&1
echo PMOS_SETUP_START
# Match postmarketOS v26.06 to Alpine 3.24 before enabling its overlay repository.
cat > /etc/apk/repositories <<'REPOS'
https://dl-cdn.alpinelinux.org/alpine/v3.24/main
https://dl-cdn.alpinelinux.org/alpine/v3.24/community
REPOS
apk update
apk upgrade --available
wget -O /tmp/postmarketos-keys.apk https://mirror.postmarketos.org/postmarketos/v26.06/aarch64/postmarketos-keys-1-r1.apk
apk add --allow-untrusted /tmp/postmarketos-keys.apk
sed -i '1ihttps://mirror.postmarketos.org/postmarketos/v26.06' /etc/apk/repositories
apk update
apk add postmarketos-base postmarketos-base-openrc postmarketos-ui-phosh mesa-dri-gallium mesa-egl mesa-gles dbus-x11
apk add gnome-control-center gnome-session wlr-randr
id user >/dev/null 2>&1 || adduser -D -u 10000 user
if [ "${ALPINEIOS_DOWNLOADABLE:-0}" = 1 ]; then
    apk add curl
    # Remove credentials belonging to the build machine from the public image.
    printf 'alpine:!\nuser:!\nroot:!\n' | busybox chpasswd -e
else
    apk add gnome-console firefox nautilus
    # Use the console password generated by provision_alpine.py for this image.
    password_hash="$(awk -F: '$1 == "alpine" { print $2; exit }' /etc/shadow)"
    case "$password_hash" in
        \$*) printf 'user:%s\n' "$password_hash" | busybox chpasswd -e ;;
        *) echo "Missing provisioned Alpine console password" >&2; exit 1 ;;
    esac
fi
for group in wheel audio video input netdev plugdev; do
    addgroup user "$group" 2>/dev/null || true
done
printf 'permit :wheel\n' > /etc/doas.d/zz-alpineios.conf
chmod 600 /etc/doas.d/zz-alpineios.conf
rc-update add dbus default
rc-service dbus start || true
rc-update del greetd default 2>/dev/null || true
rc-update del tinydm default 2>/dev/null || true
